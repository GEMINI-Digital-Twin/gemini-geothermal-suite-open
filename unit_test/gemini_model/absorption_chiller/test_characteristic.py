"""RC-05 Method B (characteristic equation) and its calibration to Method A."""

import numpy as np
import pytest

from gemini_model.absorption_chiller import characteristic, ghc1989


def test_delta_delta_t_formula():
    """ΔΔt = (t_G - t_AC) - B (t_AC - t_E)."""
    assert characteristic.delta_delta_t_k(80.0, 30.0, 10.0, 1.15) == pytest.approx(27.0)


def test_calibration_reproduces_the_documented_coefficients():
    """The helper reproduces the coefficients documented in the module and REFERENCE.md."""
    coefficients = characteristic.calibrate_to_ghc1989()
    for key, documented in characteristic.DOCUMENTED_COEFFICIENTS.items():
        assert coefficients[key] == pytest.approx(documented, rel=1e-4), key


def test_calibration_report_within_five_percent_on_rating_points():
    """RC-05: Method B calibrated at rating points reproduces Method A within ± 5 %."""
    _, report = characteristic.calibrate_to_ghc1989(with_report=True)
    assert report["max_rel_error_capacity"] < 0.05
    assert report["max_rel_error_cop"] < 0.05
    # Actual fit quality (documented in the module docstring): 1.0 % and 2.1 %.
    assert report["max_rel_error_capacity"] == pytest.approx(0.0096, abs=0.0005)
    assert report["max_rel_error_cop"] == pytest.approx(0.0209, abs=0.0005)
    low, high = report["ddt_range_k"]
    assert (low, high) == (pytest.approx(21.06, abs=0.01), pytest.approx(54.39, abs=0.01))


def test_fit_recovers_known_coefficients():
    """A fit to points generated by known coefficients returns those coefficients."""
    truth = {"s_e_per_k": 0.03, "ddt_min_k": 8.0, "s_g_per_k": 0.045, "ddt_min_g_k": 6.0}
    ddt = np.linspace(15.0, 45.0, 7)
    capacity = truth["s_e_per_k"] * (ddt - truth["ddt_min_k"])
    drive = truth["s_g_per_k"] * (ddt - truth["ddt_min_g_k"])
    fitted = characteristic.fit_coefficients(ddt, capacity, capacity / drive)
    for key, value in truth.items():
        assert fitted[key] == pytest.approx(value, rel=1e-9), key


def test_rating_delta_delta_t_uses_circuit_mean_temperatures():
    """ΔΔt at a rating point uses T_hw - 7.2/2, T_cw + 5/2 and T_chw + 6/2 (°C)."""
    expected = characteristic.delta_delta_t_k(
        ghc1989.degf_to_degc(200.0) - 3.6,
        ghc1989.degf_to_degc(85.0) + 2.5,
        ghc1989.degf_to_degc(44.0) + 3.0,
        1.15,
    )
    assert float(characteristic.rating_delta_delta_t_k(200.0)) == pytest.approx(expected)


def test_method_b_differs_from_method_a_off_the_rating_line():
    """Documented: off the 44/85 °F line the product form F_T F_c and ΔΔt diverge.

    Method A keeps the zero-capacity drive temperature fixed (71.4 °C) whatever the
    cooling-water temperature; the ΔΔt form moves it. At 180 °F, 50/75 °F the two differ by
    ≈ 0.27 of nominal capacity (REFERENCE.md); this is why the ± 5 % check is on the rating
    points only (RC-05).
    """
    c = characteristic.calibrate_to_ghc1989()
    ddt = float(
        characteristic.rating_delta_delta_t_k(180.0, chilled_water_degf=50.0, cooling_water_degf=75)
    )
    method_b = c["s_e_per_k"] * (ddt - c["ddt_min_k"])
    method_a = ghc1989.capacity_fraction(180.0, 50.0, 75.0)
    assert method_b - method_a == pytest.approx(0.27, abs=0.01)


@pytest.mark.parametrize(
    "bad, message",
    [
        ({"s_e_per_k": 0.02, "ddt_min_k": 9.0, "s_g_per_k": 0.03}, "missing"),
        ({"s_e_per_k": -0.02, "ddt_min_k": 9.0, "s_g_per_k": 0.03, "ddt_min_g_k": 7.0}, "> 0"),
        ({"s_e_per_k": 0.02, "ddt_min_k": 7.0, "s_g_per_k": 0.03, "ddt_min_g_k": 9.0}, "<="),
        (
            {"s_e_per_k": float("nan"), "ddt_min_k": 9, "s_g_per_k": 0.03, "ddt_min_g_k": 7},
            "finite",
        ),
    ],
)
def test_invalid_coefficients_are_rejected(bad, message):
    """Coefficient dicts must be complete, finite, with positive slopes and m_G <= m_E."""
    with pytest.raises(ValueError, match=message):
        characteristic.validate_coefficients(bad)
