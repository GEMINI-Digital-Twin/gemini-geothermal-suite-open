"""Build and run real GEMINI simulator projects (.json) for one doublet.

This is where the agent uses the GEMINI digital twin directly.
configure_doublet_project fills in GEMINI's own template
(simulator_examples/projects/doublet_plant.json) and run_project solves it
with gemini_simulator.

GEMINI solves the flow rate itself (nodal analysis), so we can't just set it.
To get a target flow we adjust the ESP frequency until the solved flow matches,
the same way an operator would.
"""

import copy
import json
from pathlib import Path

from scipy.optimize import brentq

from . import subsurface as sub
from .config import REPO_ROOT

TEMPLATE = REPO_ROOT / "simulator_examples" / "projects" / "doublet_plant.json"

from gemini_simulator import kpi  # noqa: E402  (sys.path set by subsurface)
from gemini_simulator.project_loader import build_project  # noqa: E402


def _trajectory(cfg, depth_m):
    return [
        {"MD": 0, "TVD": 0, "ID": cfg.well_id_m},
        {"MD": depth_m, "TVD": depth_m, "ID": cfg.well_id_m},
    ]


def configure_doublet_project(cfg, depth_m, esp_freq_hz, esp_stages=20,
                              secondary_return_c=None, secondary_flow_m3h=None,
                              hx_ua_w_per_k=None, wellhead_temperature_c=None,
                              flow_for_wellhead_t_m3h=300.0):
    """Return a GEMINI project dict for one doublet with hackathon inputs.

    We change: reservoir pressure (same for both wells), PI, well depth,
    wellhead temperature (GEMINI needs it as an input), the separator gas
    ratio from the GLR and the heating value of the 80/20 CH4/CO2 gas.
    """
    with open(TEMPLATE, "r", encoding="utf-8") as f:
        p = copy.deepcopy(json.load(f))
    if secondary_return_c is None:
        secondary_return_c = cfg.t_heat_return
    if wellhead_temperature_c is None:
        wellhead_temperature_c = sub.wellhead_temperature_c(cfg, depth_m, flow_for_wellhead_t_m3h)
    pi = sub.productivity_index_m3h_bar(cfg, cfg.well_spacing_m, cfg.skin_producer)
    ii = sub.productivity_index_m3h_bar(cfg, cfg.well_spacing_m, cfg.skin_injector)
    p_res = sub.reservoir_pressure_bar(cfg, depth_m)
    gas = sub.gas_properties(cfg)
    c = p["components"]

    prod = c["producer_well"]["parameters"]
    prod.update({
        "reservoir_pressure_bar": p_res,
        "productivity_index_m3h_per_bar": pi,
        "ambient_temperature_c": sub.reservoir_temperature_c(cfg, depth_m / 2),
        "trajectory_table": _trajectory(cfg, depth_m),
        "esp_freq_hz": esp_freq_hz,
        "roughness_m": cfg.roughness_m,
        # GEMINI's default bracket (0.01, 700) m3/h lets brentq land on a spurious
        # root where the ESP polynomial turns back up and the intake pressure is 0.
        "flow_bracket_m3h": (1.0, 350.0),
    })
    prod["esp"]["no_stages"] = esp_stages

    inj = c["injector_well"]["parameters"]
    inj.update({
        "reservoir_pressure_bar": p_res,
        "productivity_index_m3h_per_bar": ii,
        "trajectory_table": _trajectory(cfg, depth_m),
        "roughness_m": cfg.roughness_m,
    })
    inj["injector_pump"]["efficiency_factor"] = cfg.pump_eff

    # GEMINI's separator ratio is a mass ratio gas/water (template 0.5 is illustrative).
    c["separator"]["parameters"]["gas_water_ratio"] = cfg.glr * gas["density_kg_nm3"] / cfg.rho
    c["separator"]["parameters"]["gas_density"] = gas["density_kg_nm3"]
    for unit in ("boiler", "chp"):
        c[unit]["parameters"]["caloric_value"] = gas["lhv_mj_per_kg"] * 1e6
    if hx_ua_w_per_k is not None:  # default: GEMINI template value
        c["heat_exchanger"]["parameters"]["heat_transfer_coefficient"] = hx_ua_w_per_k

    for b in p["boundary_inputs"]:
        if b["component"] == "producer_well" and b["key"] == "wellhead_pressure":
            b["value"] = cfg.wellhead_pressure_bar
        if b["component"] == "producer_well" and b["key"] == "wellhead_temperature":
            b["value"] = wellhead_temperature_c
        if b["key"] in ("secondary_temperature_in", "temperature_in"):
            b["value"] = secondary_return_c
        if b["component"] == "secondary_splitter" and secondary_flow_m3h is not None:
            b["value"] = secondary_flow_m3h / 3600
    p["_description"] = (
        f"Hackathon doublet at {depth_m:.0f} m, generated by hackathon/models/gemini_project.py "
        f"from GEMINI's doublet_plant.json template."
    )
    return p


def run_project(cfg, project):
    """Solve a GEMINI project with brine properties; return KPIs in MW / C / bar."""
    with sub.brine_properties(cfg):
        solver = build_project(project)
        solver.run()
    q_m3h = solver.get_output("producer_well", "flow_rate")
    q_m3s = solver.get_output("producer_well", "flow_rate_m3s")
    sec_flow = next(b["value"] for b in project["boundary_inputs"]
                    if b["component"] == "secondary_splitter")
    sec_t_in = next(b["value"] for b in project["boundary_inputs"]
                    if b["key"] == "secondary_temperature_in")
    return {
        "flow_m3h": q_m3h,
        "wellhead_temperature_c": solver.get_output("producer_well", "temperature_out"),
        "esp_power_mw": solver.get_output("producer_well", "esp_power_el") / 1e6,
        "esp_intake_pressure_bar": solver.get_output("producer_well", "esp_intake_pressure"),
        "injector_wellhead_pressure_bar": solver.get_output("injector_well", "wellhead_pressure"),
        "injector_pump_power_mw": solver.get_output("injector_well", "power_el") / 1e6,
        "hx_primary_out_c": solver.get_output("heat_exchanger", "primary_temperature_out"),
        "hx_secondary_out_c": solver.get_output("heat_exchanger", "secondary_temperature_out"),
        "power_doublet_mw": kpi.doublet_thermal_power_w(solver, primary_flow_m3s=q_m3s) / 1e6,
        "power_plant_mw": kpi.plant_thermal_power_w(
            solver, secondary_flow_m3s=sec_flow, secondary_temperature_in=sec_t_in) / 1e6,
        "gas_boiler_mw": solver.get_output("boiler", "power_th") / 1e6,
    }


def tune_esp_for_flow(cfg, depth_m, target_flow_m3h, esp_stages=20, f_bounds=(30.0, 90.0), **kw):
    """ESP frequency at which GEMINI's solve gives the target flow."""
    kw.setdefault("flow_for_wellhead_t_m3h", target_flow_m3h)

    def resid(f):
        proj = configure_doublet_project(cfg, depth_m, f, esp_stages=esp_stages, **kw)
        try:
            return run_project(cfg, proj)["flow_m3h"] - target_flow_m3h
        except ValueError:
            return -target_flow_m3h  # pump too weak to lift any flow at this frequency

    lo, hi = f_bounds
    try:
        f = brentq(resid, lo, hi, xtol=0.05)
    except ValueError as exc:
        raise ValueError(
            f"No ESP frequency in {f_bounds} Hz reaches {target_flow_m3h} m3/h with "
            f"{esp_stages} stages; change stages or flow."
        ) from exc
    proj = configure_doublet_project(cfg, depth_m, f, esp_stages=esp_stages, **kw)
    out = run_project(cfg, proj)
    out.update({"esp_freq_hz": f, "esp_stages": esp_stages})
    return out, proj


def save_project(project, path):
    """Write a project dict as a GEMINI .json file."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(project, f, indent=2)
    return str(path)
