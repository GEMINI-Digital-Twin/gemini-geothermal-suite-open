"""What-if on a finished run (post-submission feature, FINAL_SPRINT §B).

``cli whatif --run-id <id> --runs-dir runs/final --set DB-31=65 [--set …] [--budget quick|full]``

The what-if loads the selected design of a finished run (``events.sqlite`` state,
``session/sized_designs.json``, ``run_summary.json``), applies one or more *bounded* design
levers, reruns the TL-12 year + TL-14 economics (+ CO₂ vs C0, exergy KPI) and the DesignGuard /
DesignVerifier on the changed design, and prints a before → after table of the ``KPISet``. It
writes ``runs/<id>/whatif/<n>/`` (JSON + Markdown + a DR-style record ``DR-W<n>``). The run's
own artefacts are never touched: the what-if works in its own folder with its own
``ToolContext`` and its own scenario copy of ``config/``.

Levers (register ids or TL-15 case keys; no new physics — every lever is applied the way the
TL-15 ``Scenario`` applies it, see :data:`LEVERS`):

* ``DB-31`` heating return °C and ``DB-32`` cooling return °C: candidate fields (the plant is
  regenerated by TL-09 at the selected sizes, as the TL-15 DB-31 cases do);
* ``DB-30`` ``A`` | ``B``: the TL-12 availability interpretation (B drops the outage schedule);
* ``ECO-CO2-GAS`` kg/GJ and ``CHP-EL-FRAC``: register edits in the scenario copy of ``config/``;
* ``OPT-ROBUST-BACKUP`` ``on`` | ``off``: install / remove the TL-15 robust backup nameplates
  (the run's ``uncertainty_<id>.json``), as the P8 ``robust_backup`` step does;
* ``design_flow_m3h`` and ``doublets``: candidate fields checked by the DesignGuard (DB-10/11);
* ``concept``: re-pick one of the run's screened candidates (or sized designs) by id or concept.

Bounds come from the register (value + ``sensitivity`` list of the entry), ``limits.yaml`` (the
guard) and the run (screened candidates); an out-of-limit lever is refused with that reason
(:class:`WhatIfRefused`) and nothing is written. Before and after are evaluated on the same
budget and year basis (``RUN-BUDGET``: ``quick`` = full year, ``full`` = also the TL-15 Monte
Carlo for P(demand met), ``smoke`` = CI day subset), so the deltas are like for like; the KPIs
the run recorded are reported next to them for reference.

Source: spec §9.3 (TL-15 cases), §10.1 (verifier), AG-07 (Decision Records); FINAL_SPRINT §B.
"""

