class ToolEvidence(StrictModel):
    """One tool result written under ``whatif/<n>/tool_results/`` (DR-W evidence)."""

    id: str
    tool: str
    candidate_id: str
    ok: bool
    summary: str = ""
    error: str | None = None
    path: str | None = None
    data_keys: list[str] = Field(default_factory=list)


class WhatIfOutcome(StrictModel):
    """Before or after: the design, its KPIs and the guard / verifier verdict."""

    label: Literal["before", "after"]
    candidate: Candidate
    outage_start_indices: list[int] | None = None
    status: str = Field(description="TL-13 evaluation status: ok, rejected, infeasible.")
    reason: str = ""
    guard_approved: bool
    guard_reason: str
    kpis: KPISet | None = None
    year_mode: str = ""
    objective_per_mwh: float | None = None
    limit_breaches: list[str] = Field(default_factory=list)
    verdict: DesignVerdict | None = None
    violations: list[str] = Field(default_factory=list)
    verifier_summary: str = ""
    required_backup_mw: dict[str, float] = Field(
        default_factory=dict,
        description="Backup nameplate that would meet the unmet demand: installed + largest "
        "daily unmet MW (TL-15 required_* rule; cap-only units, OPT-SPACE).",
    )
    probability_demand_met: float | None = None
    probability_source: str = ""
    evidence: list[ToolEvidence] = Field(default_factory=list)

    @property
    def meets_demand(self) -> bool:
        """Status ok, no hard-limit breach and no unmet heating/cooling energy."""
        k = self.kpis
        return (
            self.status == "ok"
            and not self.limit_breaches
            and k is not None
            and (k.unmet_heating_mwh or 0.0) <= 0.0
            and (k.unmet_cooling_mwh or 0.0) <= 0.0
        )


@dataclass
class _Workspace:
    """Where one outcome is evaluated (own ToolContext; never the run's folder)."""

    toolbox: Toolbox
    context: ToolContext
    prefix: str
    out_dir: Path
    evidence: list[ToolEvidence] = field(default_factory=list)

    def run(self, tool: str, args: dict[str, Any], candidate_id: str) -> Any:
        """Execute a tool, write its result as ``TR-W<n>-<k>_<tool>.json``; raise on failure."""
        tr_id = f"{self.prefix}-{len(self.evidence) + 1:02d}"
        try:
            result = self.toolbox.execute(tool, args, self.context)
        except Exception as exc:
            self.evidence.append(
                ToolEvidence(
                    id=tr_id,
                    tool=tool,
                    candidate_id=candidate_id,
                    ok=False,
                    error=f"{type(exc).__name__}: {exc}"[:300],
                )
            )
            raise
        folder = self.out_dir / "tool_results"
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{tr_id}_{tool}.json"
        path.write_text(json.dumps(result.model_dump(mode="json"), indent=1), encoding="utf-8")
        self.evidence.append(
            ToolEvidence(
                id=tr_id,
                tool=tool,
                candidate_id=candidate_id,
                ok=True,
                summary=result.summary,
                path=str(path.relative_to(self.out_dir)),
                data_keys=result_keys(result.data),
            )
        )
        return result.data


def _evaluate(
    space: _Workspace,
    label: Literal["before", "after"],
    candidate: Candidate,
    outages: list[int] | None,
    *,
    rerun_tl15: bool,
    recorded_probability: float | None = None,
    recorded_source: str = "",
) -> WhatIfOutcome:
    """Guard → TL-12 fast year → TL-12 full year + TL-14 (+ CO₂, exergy) → verifier (→ TL-15)."""
    session = space.toolbox.session  # type: ignore[attr-defined]
    cid = candidate.id
    guard = DesignGuard.from_config(space.context.config_dir).validate(candidate)
    outcome = WhatIfOutcome(
        label=label,
        candidate=candidate,
        outage_start_indices=outages,
        status="rejected" if not guard.approved else "ok",
        reason="" if guard.approved else f"TL-10 {guard.reason}",
        guard_approved=guard.approved,
        guard_reason=guard.reason,
        probability_demand_met=recorded_probability,
        probability_source=recorded_source if recorded_probability is not None else "",
    )
    if not guard.approved:
        outcome.evidence = space.evidence
        return outcome
    try:
        batch = space.run("simulate_annual", {"candidate_id": cid, "mode": "fast"}, cid)
        screened: DesignEvaluation = session.memo(space.context).screen[cid].evaluation
        outcome.status, outcome.reason = screened.status, screened.reason
        outcome.objective_per_mwh = screened.objective_per_mwh
        outcome.limit_breaches = list(screened.limit_breaches)
        sizes = candidate.equipment_sizes
        for key, unmet in (
            ("peak_boiler_mw", screened.max_daily_unmet_heating_mw),
            ("electric_chiller_mw", screened.max_daily_unmet_cooling_mw),
        ):
            if unmet:
                installed = sizes.get(key, screened.right_sized_mw.get(key, 0.0))
                outcome.required_backup_mw[key] = round(installed + unmet, 3)
        if screened.status != "ok":
            outcome.guard_approved = "TL-10" not in screened.reason
            if not outcome.guard_approved:
                outcome.guard_reason = screened.reason
            outcome.evidence = space.evidence
            return outcome
        full = space.run("simulate_annual", {"candidate_id": cid, "mode": "full"}, cid)
        outcome.kpis = full.kpis[0] if full.kpis else (batch.kpis[0] if batch.kpis else None)
        outcome.year_mode = "full"
        report = space.run("verify_design", {"candidate_id": cid}, cid)
        outcome.verdict = report.verdict
        outcome.violations = list(report.violations)
        outcome.verifier_summary = report.summary
        if rerun_tl15:
            unc = space.run("uncertainty", {"candidate_id": cid}, cid)
            outcome.probability_demand_met = unc.probability_demand_met
            outcome.probability_source = f"TL-15 rerun ({unc.samples} samples)"
            if outcome.kpis is not None and unc.percentiles:
                outcome.kpis = outcome.kpis.model_copy(update={"percentiles": unc.percentiles})
    except Exception as exc:  # noqa: BLE001 - reported as the outcome, never a crash
        if outcome.status == "ok":
            outcome.status = "infeasible"
        outcome.reason = (outcome.reason or f"{type(exc).__name__}: {exc}")[:300]
    outcome.evidence = space.evidence
    return outcome


def _workspace(
    *,
    out_dir: Path,
    prefix: str,
    run_id: str,
    budget: str,
    config_dir: Path | None,
    cache: DesignCache,
    candidates: Sequence[Candidate],
    designs: Mapping[str, SizedDesign],
    answers: Mapping[str, JsonValue],
) -> _Workspace:
    """Toolbox + context whose run folder is the what-if folder (sized designs pre-registered)."""
    session_dir = out_dir / SESSION_DIR
    session_dir.mkdir(parents=True, exist_ok=True)
    sized_path = session_dir / "sized_designs.json"
    known = json.loads(sized_path.read_text(encoding="utf-8")) if sized_path.is_file() else {}
    known.update({k: v.model_dump(mode="json", exclude={"evaluation"}) for k, v in designs.items()})
    sized_path.write_text(json.dumps(known, indent=1), encoding="utf-8")
    toolbox = real_toolbox(make_profile(budget, config_dir=config_dir), cache=cache)
    context = ToolContext(
        run_id=run_id,
        run_dir=out_dir,
        config_dir=config_dir,
        candidates=tuple(candidates),
        answers=dict(answers),
        selected_id=candidates[-1].id if candidates else None,
    )
    return _Workspace(toolbox, context, prefix, out_dir)


