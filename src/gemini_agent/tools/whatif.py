"""Catalogue of the what-if levers (ids are matched case-insensitively)."""

_FLAG_ON = {"on", "true", "yes", "1"}
_FLAG_OFF = {"off", "false", "no", "0"}


class UnknownLever(ValueError):
    """A ``--set`` names no lever (the message lists the valid ones)."""


class WhatIfRefused(ValueError):
    """A lever is outside its bound; the message is the guard's / register's reason."""


def lever_help() -> str:
    """One line per lever (CLI help and the unknown-lever message)."""
    lines = []
    for spec in LEVERS.values():
        value = "|".join(spec.choices) if spec.choices else f"<{spec.kind}>"
        unit = f" [{spec.unit}]" if spec.unit and spec.unit != "-" else ""
        lines.append(f"  {spec.id}={value}{unit}: {spec.description}; bound: {spec.bound}")
    return "\n".join(lines)


def _lever_spec(name: str) -> LeverSpec:
    key = name.strip()
    for spec in LEVERS.values():
        if spec.id.lower() == key.lower():
            return spec
    raise UnknownLever(
        f"unknown lever '{name}'. Valid levers ({', '.join(LEVERS)}):\n{lever_help()}"
    )


def _coerce(spec: LeverSpec, raw: Any) -> Any:
    """Typed value of a lever (ValueError with the reason if the text does not parse)."""
    text = str(raw).strip()
    if spec.kind == "float":
        try:
            return float(text)
        except ValueError:
            raise ValueError(f"{spec.id}: expected a number, got '{text}'") from None
    if spec.kind == "int":
        try:
            value = int(text)
        except ValueError:
            raise ValueError(f"{spec.id}: expected an integer, got '{text}'") from None
        return value
    if spec.kind == "choice":
        for choice in spec.choices:
            if text.lower() == choice.lower():
                return choice
        raise ValueError(f"{spec.id}: expected one of {', '.join(spec.choices)}, got '{text}'")
    if spec.kind == "flag":
        if isinstance(raw, bool):
            return raw
        if text.lower() in _FLAG_ON:
            return True
        if text.lower() in _FLAG_OFF:
            return False
        raise ValueError(f"{spec.id}: expected on|off, got '{text}'")
    return text  # candidate id / concept


def parse_levers(items: Sequence[str] | Mapping[str, Any]) -> dict[str, Any]:
    """``LEVER=value`` strings (or a mapping) → ``{lever id: typed value}`` (catalogue order)."""
    pairs: list[tuple[str, Any]] = []
    if isinstance(items, Mapping):
        pairs = list(items.items())
    else:
        for item in items:
            name, sep, value = str(item).partition("=")
            if not sep or not name.strip():
                raise UnknownLever(
                    f"expected LEVER=value, got '{item}'. Valid levers:\n{lever_help()}"
                )
            pairs.append((name, value))
    parsed: dict[str, Any] = {}
    for name, value in pairs:
        spec = _lever_spec(name)
        if spec.id in parsed:
            raise ValueError(f"lever {spec.id} given twice")
        parsed[spec.id] = _coerce(spec, value)
    return {spec_id: parsed[spec_id] for spec_id in LEVERS if spec_id in parsed}


def format_levers(levers: Mapping[str, Any]) -> str:
    """``DB-31=65, doublets=3`` (the title of the what-if)."""

    def fmt(value: Any) -> str:
        if isinstance(value, bool):
            return "on" if value else "off"
        if isinstance(value, float):
            return f"{value:g}"
        return str(value)

    return ", ".join(f"{k}={fmt(v)}" for k, v in levers.items())


def register_range(register: Any, assumption_id: str) -> tuple[float, float]:
    """Documented range of a numeric register entry: its value and its ``sensitivity`` list."""
    entry = register.get(assumption_id)
    values: list[float] = []
    for item in [entry.value, *(entry.sensitivity if isinstance(entry.sensitivity, list) else [])]:
        if isinstance(item, int | float) and not isinstance(item, bool):
            values.append(float(item))
    if not values:
        raise ValueError(f"{assumption_id} holds no numeric value")
    return min(values), max(values)


# =========================================================================== the run
@dataclass
class RunSnapshot:
    """What the what-if reads from a finished run (nothing is written back)."""

    run_id: str
    run_dir: Path
    state: RunState
    sized: dict[str, SizedDesign]
    selected: Candidate
    analysed_id: str
    uncertainty: UncertaintyReport | None = None
    summary: dict[str, Any] = field(default_factory=dict)

    @property
    def candidates(self) -> list[Candidate]:
        """Every candidate of the run (screened concepts + sized designs)."""
        return list(self.state.candidates)

    def candidate(self, candidate_id: str) -> Candidate:
        """Candidate by id (state first, then the sized designs)."""
        for candidate in self.state.candidates:
            if candidate.id == candidate_id:
                return candidate
        sized = self.sized.get(candidate_id)
        if sized is not None:
            return sized.candidate
        raise KeyError(candidate_id)

    def outages(self, candidate_id: str) -> list[int] | None:
        """Outage schedule of a sized design (None: SIM-OUTAGE default placement)."""
        sized = self.sized.get(candidate_id)
        return list(sized.outage_start_indices) if sized and sized.outage_start_indices else None

    def parent_concept(self, candidate: Candidate) -> ConceptId | None:
        """Generator parent of C6–C8 (sized design, else the parent candidate's concept)."""
        if candidate.concept not in ("C6", "C7", "C8"):
            return None
        sized = self.sized.get(candidate.id)
        if sized is not None:
            return sized.parent_concept
        by_id = {c.id: c for c in self.state.candidates}
        parent = by_id.get(candidate.parent_id or "")
        if parent is not None and parent.concept not in ("C0", "C6", "C7", "C8"):
            return parent.concept
        return "C2"

    def c0(self) -> Candidate | None:
        """The C0 counterfactual of the run (CO₂ reduction basis)."""
        return next((c for c in self.state.candidates if c.concept == "C0"), None)

    def probability_demand_met(self) -> float | None:
        """TL-15 P(demand met) the run recorded for the selected design (robust mapping)."""
        if self.uncertainty is None:
            return None
        if self.selected.id != self.analysed_id:
            return self.uncertainty.probability_demand_met_robust
        return self.uncertainty.probability_demand_met

    def guard_reason(self, candidate_id: str) -> str:
        """Why the run's DesignGuard excluded a candidate ('' if it did not)."""
        if candidate_id not in self.state.guard_failed:
            return ""
        for record in self.state.tool_results:
            if record.tool != "design_guard" or not record.ok or not record.path:
                continue
            path = self.run_dir / record.path
            if not path.is_file():
                continue
            data = json.loads(path.read_text(encoding="utf-8")).get("data", {})
            for check in data.get("checks", []):
                if check.get("candidate_id") == candidate_id and check.get("violations"):
                    return "; ".join(str(v) for v in check["violations"])
        return "excluded by the DesignGuard in the run"


def load_run(run_dir: Path | str) -> RunSnapshot:
    """Read a finished run folder (``ValueError`` if it is not one)."""
    run_dir = Path(run_dir)
    store_path = run_dir / STORE_FILE
    if not store_path.is_file():
        raise ValueError(f"{run_dir}: not a run folder ({STORE_FILE} missing)")
    run_id = run_dir.name
    summary_path = run_dir / "run_summary.json"
    summary: dict[str, Any] = {}
    if summary_path.is_file():
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        run_id = str(summary.get("run_id", run_id))
    store = SQLiteEventStore(store_path)
    try:
        record = store.get_run(run_id)
        if record is None:
            known = [r.run_id for r in store.list_runs()]
            record = store.get_run(known[0]) if len(known) == 1 else None
        if record is None:
            raise ValueError(f"{run_dir}: run '{run_id}' not found in {STORE_FILE}")
    finally:
        store.close()
    state = RunState.model_validate(record.state)
    sized: dict[str, SizedDesign] = {}
    sized_path = run_dir / SESSION_DIR / "sized_designs.json"
    if sized_path.is_file():
        raw = json.loads(sized_path.read_text(encoding="utf-8"))
        sized = {k: SizedDesign.model_validate(v) for k, v in raw.items()}
    selected_id = state.selected_id or str(summary.get("selected_candidate") or "")
    if not selected_id:
        raise ValueError(f"{run_dir}: the run selected no design (status {state.status.value})")
    by_id = {c.id: c for c in state.candidates} | {k: v.candidate for k, v in sized.items()}
    if selected_id not in by_id:
        raise ValueError(f"{run_dir}: selected design '{selected_id}' is not in the run")
    snapshot = RunSnapshot(
        run_id=state.run_id,
        run_dir=run_dir,
        state=state,
        sized=sized,
        selected=by_id[selected_id],
        analysed_id=state.analysed_id(selected_id) or selected_id,
        summary=summary,
    )
    unc_path = run_dir / f"uncertainty_{snapshot.analysed_id}.json"
    if unc_path.is_file():
        snapshot.uncertainty = UncertaintyReport.model_validate_json(
            unc_path.read_text(encoding="utf-8")
        )
    return snapshot


def next_index(run_dir: Path) -> int:
    """``<n>`` of the next ``runs/<id>/whatif/<n>/`` folder."""
    folder = run_dir / WHATIF_DIR
    if not folder.is_dir():
        return 1
    used = [int(p.name) for p in folder.iterdir() if p.is_dir() and p.name.isdigit()]
    return max(used, default=0) + 1


# =========================================================================== applying levers
class AppliedLever(StrictModel):
    """How one lever was applied (audit trail of the what-if)."""

    lever: str
    value: JsonValue
    mechanism: str
    base_value: JsonValue = None


class WhatIfDesign(StrictModel):
    """The changed design and the TL-15 scenario it runs in."""

    candidate: Candidate
    outage_start_indices: list[int] | None = None
    parent_concept: ConceptId | None = None
    scenario: Scenario
    answers: dict[str, JsonValue] = Field(default_factory=dict)
    applied: list[AppliedLever] = Field(default_factory=list)


def _base_answers(snapshot: RunSnapshot) -> dict[str, JsonValue]:
    answers = dict(snapshot.state.answer_values())
    answers.setdefault("DB-31", snapshot.selected.heating_return_degc)
    answers.setdefault("DB-32", snapshot.selected.cooling_return_degc)
    return answers


def _pick_candidate(snapshot: RunSnapshot, text: str) -> Candidate:
    """Screened candidate / sized design by id, else the unique candidate of a concept."""
    pool = {c.id: c for c in snapshot.candidates}
    for sized_id, sized in snapshot.sized.items():
        pool.setdefault(sized_id, sized.candidate)
    for cid, candidate in pool.items():
        if cid.lower() == text.lower():
            return candidate
    concept_matches = [c for c in pool.values() if c.concept.lower() == text.lower()]
    screened = [c for c in concept_matches if c.id not in snapshot.sized]
    if len(screened) == 1:
        return screened[0]
    if len(concept_matches) == 1:
        return concept_matches[0]
    if concept_matches:
        ids = ", ".join(c.id for c in concept_matches)
        raise WhatIfRefused(f"concept '{text}' is ambiguous in the run; name one of: {ids}")
    raise WhatIfRefused(
        f"'{text}' is not a candidate of the run; screened candidates: " + ", ".join(sorted(pool))
    )


def apply_levers(
    snapshot: RunSnapshot,
    levers: Mapping[str, Any],
    *,
    index: int,
    config_dir: Path | str | None = None,
) -> WhatIfDesign:
    """Build the what-if design from the selected one (module doc); refuse out-of-limit levers."""
    levers = parse_levers(levers)
    if not levers:
        raise UnknownLever(f"no lever given. Valid levers:\n{lever_help()}")
    register = load_config("assumptions", config_dir)
    base = snapshot.selected
    candidate = base
    answers = _base_answers(snapshot)
    db30 = answers.get("DB-30")
    outages = snapshot.outages(base.id)
    parent = snapshot.parent_concept(base)
    applied: list[AppliedLever] = []
    scenario_assumptions: dict[str, JsonValue] = {}
    heating_return: float | None = None

    # --- the design to start from (concept re-pick, robust backups) -------------------------
    if "concept" in levers:
        picked = _pick_candidate(snapshot, str(levers["concept"]))
        reason = snapshot.guard_reason(picked.id)
        if reason:
            raise WhatIfRefused(f"{picked.id} was excluded in the run: {reason}")
        if picked.id in snapshot.state.rejected_ids():
            raise WhatIfRefused(f"{picked.id} was REJECTED by the DesignVerifier in the run")
        if picked.concept == "C0":
            raise WhatIfRefused("C0 is the counterfactual, not a geothermal design")
        candidate = picked
        outages = snapshot.outages(picked.id)
        parent = snapshot.parent_concept(picked)
        applied.append(
            AppliedLever(
                lever="concept",
                value=picked.id,
                base_value=base.id,
                mechanism="re-picked from the run's screened candidates / sized designs",
            )
        )
    if "OPT-ROBUST-BACKUP" in levers:
        on = bool(levers["OPT-ROBUST-BACKUP"])
        sized = snapshot.sized.get(candidate.id)
        robust_of = sized.robust_backup_of if sized else None
        if on and robust_of is None:
            report = snapshot.uncertainty
            if report is None or report.candidate_id != candidate.id or not report.robust_backup_mw:
                raise WhatIfRefused(
                    f"no TL-15 result for {candidate.id} in the run "
                    f"(uncertainty_{candidate.id}.json): robust backups unknown"
                )
            robust_mw = dict(report.robust_backup_mw)
            candidate = candidate.model_copy(
                update={
                    "id": f"{candidate.id}{ROBUST_SUFFIX}",
                    "equipment_sizes": candidate.equipment_sizes | robust_mw,
                    "description": f"{candidate.id} with the TL-15 robust backups",
                }
            )
            mechanism = f"TL-15 robust_backup_mw installed: {robust_mw}"
        elif not on and robust_of is not None:
            candidate = snapshot.candidate(robust_of)
            outages = snapshot.outages(robust_of)
            parent = snapshot.parent_concept(candidate)
            mechanism = f"robust backups removed: back to {robust_of}"
        else:
            mechanism = "already " + ("on" if on else "off") + " for this design; no change"
        applied.append(
            AppliedLever(
                lever="OPT-ROBUST-BACKUP",
                value=on,
                base_value=robust_of is not None,
                mechanism=mechanism,
            )
        )

    # --- candidate fields ------------------------------------------------------------------
    update: dict[str, Any] = {}
    if "doublets" in levers:
        update["doublets"] = int(levers["doublets"])
        mechanism = "candidate field; DesignGuard DB-10"
        if update["doublets"] != candidate.doublets and outages is not None:
            # 2026-11-04 (voice dialogue): the run's schedule has one outage per doublet of the
            # selected design; TL-12 places lowest-load windows for the new count (SIM-OUTAGE).
            outages = None
            mechanism += "; outage schedule re-placed by TL-12 for the new count (SIM-OUTAGE)"
        applied.append(
            AppliedLever(
                lever="doublets",
                value=update["doublets"],
                base_value=candidate.doublets,
                mechanism=mechanism,
            )
        )
    if "design_flow_m3h" in levers:
        update["design_flow_m3h"] = float(levers["design_flow_m3h"])
        applied.append(
            AppliedLever(
                lever="design_flow_m3h",
                value=update["design_flow_m3h"],
                base_value=candidate.design_flow_m3h,
                mechanism="candidate field; DesignGuard DB-11",
            )
        )
    for lever, field_name in (("DB-31", "heating_return_degc"), ("DB-32", "cooling_return_degc")):
        if lever not in levers:
            continue
        value = float(levers[lever])
        low, high = register_range(register, lever)
        if not low <= value <= high:
            raise WhatIfRefused(
                f"{lever} = {value:g} degC outside the register's documented range "
                f"{low:g}–{high:g} degC (value + sensitivity of {lever})"
            )
        update[field_name] = value
        answers[lever] = value
        if lever == "DB-31":
            heating_return = value
        else:
            scenario_assumptions["DB-32"] = value
        applied.append(
            AppliedLever(
                lever=lever,
                value=value,
                base_value=getattr(candidate, field_name),
                mechanism=f"candidate {field_name} (TL-15 Scenario; plant regenerated by TL-09)",
            )
        )
    if update:
        candidate = candidate.model_copy(update=update)

    # --- world / register levers ------------------------------------------------------------
    for lever in ("ECO-CO2-GAS", "CHP-EL-FRAC"):
        if lever not in levers:
            continue
        value = float(levers[lever])
        low, high = register_range(register, lever)
        if not low <= value <= high:
            raise WhatIfRefused(
                f"{lever} = {value:g} outside the register's documented range {low:g}–{high:g} "
                f"(value + sensitivity of {lever})"
            )
        scenario_assumptions[lever] = value
        applied.append(
            AppliedLever(
                lever=lever,
                value=value,
                base_value=register.get(lever).value,
                mechanism="register edit in the scenario copy of config/ (TL-15 Scenario)",
            )
        )
    if "DB-30" in levers:
        value = str(levers["DB-30"])
        applied.append(
            AppliedLever(
                lever="DB-30",
                value=value,
                base_value=db30,
                mechanism="TL-12 availability interpretation (TL-15 Scenario db30_answer)",
            )
        )
        db30 = value
        answers["DB-30"] = value
        if value == "B":
            outages = None  # TL-15 DB-30=B case: 330 days, no outage schedule

    # --- the guard decides on the candidate-level limits (DB-10, DB-11, DB-36) --------------
    guard = DesignGuard.from_config(config_dir).validate(candidate)
    if not guard.approved:
        raise WhatIfRefused(f"DesignGuard: {guard.reason}")
    candidate = candidate.model_copy(
        update={
            "id": f"{candidate.id}-w{index}",
            "description": f"what-if {index} of {snapshot.run_id}: {format_levers(levers)} "
            f"(from {candidate.id})",
        }
    )
    scenario = Scenario(
        name=f"whatif-{index}",
        assumptions=scenario_assumptions,
        heating_return_degc=heating_return,
        db30_answer=db30,
    )
    return WhatIfDesign(
        candidate=candidate,
        outage_start_indices=outages,
        parent_concept=parent,
        scenario=scenario,
        answers=answers,
        applied=applied,
    )


