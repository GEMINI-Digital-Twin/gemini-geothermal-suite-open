"""Generate a one-doublet GEMINI plant JSON file, run it and check the result.

The production pump curve is generated so the pump runs at the required 70%
hydraulic efficiency and delivers the head needed at the design flow. GEMINI's
nodal solver then finds the actual flow.
"""

import json
from pathlib import Path

from gemini_simulator.project_loader import build_project
from pipe_size_study import CP, RHO, build_well, walk
from gemini_simulator.well_flow import _split_trajectory_at_depth
from yearly_energy import CHP_EFFICIENCY

ROOT = Path(__file__).parent.parent
PLANTS_DIR = ROOT / "results" / "plants"

SURFACE_C = 12.0
GRADIENT_C_PER_M = 0.030
G = 9.81
MAX_COOLING_C = 40.0
MIN_FLOW_M3H = 50.0
MAX_FLOW_M3H = 300.0
PUMP_EFFICIENCY = 0.7

# Assumptions, see STATE.md
PIPE_ID_M = 0.20
ROUGHNESS_M = 0.0001
INDEX_M3H_PER_BAR = 13.4
ESP_DEPTH_M = 650.0
WELLHEAD_PRESSURE_BAR = 3.0
WELL_LOSS_C = 1.0
HEX_UA_W_PER_K = 2.0e6
MIN_INTAKE_BAR = 1.0

# GEMINI ESP unit conversions
M3S_TO_BBLD = 543439.650564
FT_HEAD_TO_PA = 2988.30167
BHP_TO_WATT = 745.7
CURVE_RUNOUT = 1.5  # zero-head flow as a multiple of design flow


def required_boost_bar(depth_m, flow_m3h):
    """Return the pump boost (bar) the challenge brine needs at a flow."""
    flow_m3s = flow_m3h / 3600.0
    reservoir_bar = RHO * G * depth_m / 1e5
    segment = {"angle": 90.0, "depth": depth_m, "diameter": PIPE_ID_M}
    top, bottom = _split_trajectory_at_depth([segment], ESP_DEPTH_M)
    bottomhole = reservoir_bar - flow_m3h / INDEX_M3H_PER_BAR
    intake = walk(build_well(bottom, ROUGHNESS_M), bottomhole, flow_m3s, "up")
    discharge = walk(build_well(top, ROUGHNESS_M), WELLHEAD_PRESSURE_BAR, flow_m3s, "down")
    return discharge - intake


def pump_curve(depth_m, design_flow_m3h):
    """Return GEMINI ESP coefficients for a 70%-efficient pump sized for the design flow."""
    design_bbld = design_flow_m3h / 3600.0 * M3S_TO_BBLD
    runout_bbld = CURVE_RUNOUT * design_bbld
    design_head_ft = required_boost_bar(depth_m, design_flow_m3h) * 1e5 / FT_HEAD_TO_PA
    shutoff_head_ft = design_head_ft / (1 - (1 / CURVE_RUNOUT) ** 2)
    head = [shutoff_head_ft, 0.0, -shutoff_head_ft / runout_bbld**2, 0.0, 0.0, 0.0]
    k = FT_HEAD_TO_PA / (M3S_TO_BBLD * PUMP_EFFICIENCY * BHP_TO_WATT)
    power = [0.0, k * head[0], 0.0, k * head[2], 0.0, 0.0]
    return {"no_stages": 1, "head_coeff": head, "power_coeff": power, "electricity_emission_factor": 0.3}


def trajectory(depth_m):
    """Return a vertical GEMINI trajectory table to the given depth."""
    stations = [0.0, ESP_DEPTH_M, depth_m]
    return [{"MD": md, "TVD": md, "ID": PIPE_ID_M} for md in stations]


def build_plant(depth_m, design_flow_m3h, return_c, secondary_flow_m3h, gas_to_chp=False):
    """Return a GEMINI plant JSON dict for one doublet.

    ``gas_to_chp`` sends the produced gas to the CHP instead of the boiler.
    """
    reservoir_bar = RHO * G * depth_m / 1e5
    well = {
        "reservoir_pressure_bar": reservoir_bar,
        "productivity_index_m3h_per_bar": INDEX_M3H_PER_BAR,
        "trajectory_table": trajectory(depth_m),
        "roughness_m": ROUGHNESS_M,
    }
    fluid = {"fluid_density": RHO, "specific_heat": CP}
    gas = {"caloric_value": 29.66e6, "efficiency_factor": 0.8, "gas_emission_factor": 68.6}
    return {
        "_description": (
            f"Generated by the agent: one doublet, {depth_m:.0f} m, design flow "
            f"{design_flow_m3h:.0f} m3/h, return {return_c:.0f} C, secondary "
            f"{secondary_flow_m3h:.0f} m3/h."
        ),
        "components": {
            "producer_well": {
                "type": "producer_well",
                "parameters": {
                    **well,
                    "ambient_temperature_c": SURFACE_C,
                    "esp_depth_m": ESP_DEPTH_M,
                    "esp": pump_curve(depth_m, design_flow_m3h),
                    "esp_freq_hz": 60.0,
                },
            },
            "injector_well": {
                "type": "injector_well",
                "parameters": {
                    **well,
                    "injector_pump": {"efficiency_factor": PUMP_EFFICIENCY, "electricity_emission_factor": 0.3},
                },
            },
            "separator": {
                "type": "separator",
                "parameters": {"flow_resistance": 3.6, "temperature_drop": 1, "gas_water_ratio": 0.8, "gas_density": 0.965},
            },
            "filter_a": {
                "type": "filter",
                "parameters": {"base_resistance": 36.0, "fouling_coeff_a": 18.0, "fouling_coeff_b": 0.036, "temperature_drop": 1},
            },
            "heat_exchanger": {
                "type": "heat_exchanger",
                "parameters": {"flow_resistance": 0, "flow_configuration": "counter", "heat_transfer_coefficient": HEX_UA_W_PER_K, **fluid},
            },
            "filter_b": {
                "type": "filter",
                "parameters": {"base_resistance": 3.6, "fouling_coeff_a": 18.0, "fouling_coeff_b": 0.036, "temperature_drop": 1},
            },
            "boiler": {"type": "boiler", "parameters": {**gas, **fluid}},
            "chp": {"type": "chp", "parameters": {**gas, **fluid, "efficiency_factor": CHP_EFFICIENCY}},
            "secondary_splitter": {"type": "splitter", "parameters": {"split_fractions": [1.0, 0.0]}},
            "gas_splitter": {"type": "splitter", "parameters": {"split_fractions": [0.0, 1.0] if gas_to_chp else [1.0, 0.0]}},
            "water_mixer": {"type": "mixer", "parameters": {"num_inputs": 2}},
        },
        "boundary_inputs": [
            {"component": "producer_well", "key": "wellhead_pressure", "value": WELLHEAD_PRESSURE_BAR},
            {"component": "producer_well", "key": "wellhead_temperature", "value": wellhead_temperature(depth_m)},
            {"component": "secondary_splitter", "key": "input", "value": secondary_flow_m3h / 3600.0},
            {"component": "heat_exchanger", "key": "secondary_temperature_in", "value": return_c},
            {"component": "chp", "key": "temperature_in", "value": return_c},
        ],
        "connections": CONNECTIONS,
    }


def wellhead_temperature(depth_m):
    """Return the assumed wellhead temperature (C) for a reservoir depth."""
    return SURFACE_C + GRADIENT_C_PER_M * depth_m - WELL_LOSS_C


def run_plant(depth_m, design_flow_m3h, return_c, secondary_flow_m3h):
    """Write, run and check a one-doublet plant, returning a compact result."""
    plant = build_plant(depth_m, design_flow_m3h, return_c, secondary_flow_m3h)
    PLANTS_DIR.mkdir(parents=True, exist_ok=True)
    name = f"plant_{depth_m:.0f}m_Q{design_flow_m3h:.0f}_R{return_c:.0f}_S{secondary_flow_m3h:.0f}.json"
    path = PLANTS_DIR / name
    path.write_text(json.dumps(plant, indent=2), encoding="utf-8")

    solver = build_project(json.loads(path.read_text(encoding="utf-8")))
    solver.run()
    get = solver.get_output

    flow_m3h = get("producer_well", "flow_rate")
    injected_m3h = get("injector_well", "flow_rate_m3s") * 3600.0
    t_wellhead = get("producer_well", "temperature_out")
    t_hex_in = get("filter_a", "temperature_out")
    t_hex_out = get("heat_exchanger", "primary_temperature_out")
    t_injected = get("filter_b", "temperature_out")
    duty_w = get("heat_exchanger", "heat_duty")
    brine_heat_w = flow_m3h / 3600.0 * RHO * CP * (t_hex_in - t_hex_out)
    intake = get("producer_well", "esp_intake_pressure")
    supply_c = get("water_mixer", "temperature")

    checks = {
        "flow_within_50_300": MIN_FLOW_M3H <= flow_m3h <= MAX_FLOW_M3H,
        "brine_cooling_max_40": t_wellhead - t_injected <= MAX_COOLING_C,
        "equal_production_injection": abs(flow_m3h - injected_m3h) < 1e-6,
        "pump_intake_above_minimum": intake is not None and intake >= MIN_INTAKE_BAR,
        "heat_exchanger_energy_balance": abs(duty_w - brine_heat_w) <= 1e-6 * max(duty_w, 1.0),
        "heat_exchanger_second_law": get("heat_exchanger", "secondary_temperature_out") <= t_hex_in,
    }
    return {
        "plant_file": str(path.relative_to(ROOT)),
        "flow_m3h": round(flow_m3h, 1),
        "wellhead_c": round(t_wellhead, 1),
        "injected_c": round(t_injected, 1),
        "brine_cooling_c": round(t_wellhead - t_injected, 1),
        "heat_exchanger_mw": round(duty_w / 1e6, 2),
        "produced_gas_heat_mw": round(get("boiler", "power_th") / 1e6, 2),
        "supply_before_backup_c": round(supply_c, 1),
        "production_pump_mw": round(get("producer_well", "esp_power_el") / 1e6, 3),
        "injection_pump_mw": round(get("injector_well", "power_el") / 1e6, 3),
        "pump_intake_bar": None if intake is None else round(intake, 1),
        "checks_failed": [name for name, passed in checks.items() if not passed],
    }


